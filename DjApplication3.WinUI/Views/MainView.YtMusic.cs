        private async void YtMusicButton_Click(object sender, RoutedEventArgs e)
        {
            if (YtMusicDataSource.isConnected())
            {
                YtMusicDataSource.removeConnect();
                UpdateYtMusicButton();
                ViewModel.Status = "Connexion YouTube Music supprimée.";
                return;
            }

            LoginPanel.Visibility = Visibility.Visible;
            ContinueYtMusicButton.IsEnabled = false;

            try
            {
                var version = CoreWebView2Environment.GetAvailableBrowserVersionString();
                LogWebViewState($"Ouverture de la connexion avant layout; runtime={version}");
                if (string.IsNullOrWhiteSpace(version))
                {
                    throw new InvalidOperationException("Runtime Microsoft Edge WebView2 introuvable.");
                }

                await EnsureLoginWebViewReadyAsync();
                _loginWebView!.Source = new Uri(
                    "https://accounts.google.com/ServiceLogin?continue=https%3A%2F%2Fmusic.youtube.com%2F");
                LogWebViewState("Navigation de connexion demandée");
            }
            catch (COMException ex)
            {
                LoginPanel.Visibility = Visibility.Collapsed;
                ViewModel.Status = $"WebView2 indisponible: {ex.Message}";
                AppLogger.Error(ex, "WebView2 unavailable for Youtube Music login");
            }
            catch (Exception ex)
            {
                LoginPanel.Visibility = Visibility.Collapsed;
                ViewModel.Status = $"Ouverture YouTube Music impossible: {ex.Message}";
                AppLogger.Error(ex, "Open Youtube Music login failed");
            }
        }

        private async void ContinueYtMusicButton_Click(object sender, RoutedEventArgs e)
        {
            try
            {
                await EnsureLoginWebViewReadyAsync();

                var cookieManager = _loginWebView!.CoreWebView2.CookieManager;
                var cookies = new List<CoreWebView2Cookie>();
                foreach (var url in new[]
                {
                    "https://music.youtube.com",
                    "https://www.youtube.com",
                    "https://youtube.com"
                })
                {
                    cookies.AddRange(await cookieManager.GetCookiesAsync(url));
                }

                cookies = cookies
                    .Where(cookie => IsYoutubeDomain(cookie.Domain))
                    .GroupBy(cookie => $"{cookie.Domain}|{cookie.Path}|{cookie.Name}", StringComparer.OrdinalIgnoreCase)
                    .Select(group => group.First())
                    .ToList();

                var cookieData = cookies.Select(cookie => new CookieModel
                {
                    Name = cookie.Name,
                    Value = cookie.Value,
                    Path = cookie.Path,
                    Domain = cookie.Domain
                }).ToList();

                if (!YtMusicCookieSession.TryCreate(cookieData, out _))
                {
                    ViewModel.Status = "Connexion incomplète. Termine la connexion sur YouTube Music puis réessaie.";
                    return;
                }

                var netscapeCookies = new StringBuilder();
                netscapeCookies.AppendLine("# Netscape HTTP Cookie File");
                netscapeCookies.AppendLine("# This file is generated by DjApplication3 - do not edit.");
                foreach (var cookie in cookies)
                {
                    var includeSubdomains = cookie.Domain.StartsWith('.') ? "TRUE" : "FALSE";
                    var secure = cookie.IsSecure ? "TRUE" : "FALSE";
                    netscapeCookies.AppendLine(
                        $"{cookie.Domain}\t{includeSubdomains}\t{cookie.Path}\t{secure}\t0\t{cookie.Name}\t{cookie.Value}");
                }

                SaveCookieFiles(cookieData, netscapeCookies.ToString());

                LoginPanel.Visibility = Visibility.Collapsed;
                ViewModel.Status = "Connexion YouTube Music réussie.";
                UpdateYtMusicButton();
                await ViewModel.LoadPlaylistsAsync();
            }
            catch (Exception ex)
            {
                ViewModel.Status = $"Connexion YouTube Music impossible: {ex.Message}";
                AppLogger.Error(ex, "Youtube Music cookie export failed");
            }
        }

        private async Task EnsureLoginWebViewReadyAsync()
        {
            await WaitForLoginWebViewHostLayoutAsync();

            if (_loginWebView == null)
            {
                _loginWebView = new WebView2
                {
                    HorizontalAlignment = HorizontalAlignment.Stretch,
                    VerticalAlignment = VerticalAlignment.Stretch
                };
                _loginWebView.CoreWebView2Initialized += LoginWebView_CoreWebView2Initialized;
                _loginWebView.NavigationStarting += LoginWebView_NavigationStarting;
                _loginWebView.NavigationCompleted += LoginWebView_NavigationCompleted;
                _loginWebView.CoreProcessFailed += LoginWebView_CoreProcessFailed;
                LoginWebViewHost.Children.Add(_loginWebView);
                LogWebViewState("Contrôle WebView2 créé");
            }

            await WaitForLoginWebViewLayoutAsync();

            if (_loginWebView.CoreWebView2 == null)
            {
                var initialized = new TaskCompletionSource<Exception?>(TaskCreationOptions.RunContinuationsAsynchronously);
                void InitializedHandler(WebView2 _, CoreWebView2InitializedEventArgs args)
                {
                    initialized.TrySetResult(args.Exception);
                }

                _loginWebView.CoreWebView2Initialized += InitializedHandler;
                try
                {
                    LogWebViewState("Début EnsureCoreWebView2Async");
                    await _loginWebView.EnsureCoreWebView2Async();
                    if (_loginWebView.CoreWebView2 == null && !initialized.Task.IsCompleted)
                    {
                        await initialized.Task.WaitAsync(TimeSpan.FromSeconds(15));
                    }

                    if (initialized.Task.IsCompletedSuccessfully
                        && initialized.Task.Result is Exception initializationException)
                    {
                        throw new InvalidOperationException(
                            "L'initialisation de WebView2 a échoué.",
                            initializationException);
                    }
                }
                finally
                {
                    _loginWebView.CoreWebView2Initialized -= InitializedHandler;
                }
            }

            if (_loginWebView.CoreWebView2 == null)
            {
                LogWebViewState("Échec: CoreWebView2 est null après initialisation");
                throw new InvalidOperationException(
                    "WebView2 n'est pas prêt après son initialisation. Consulte outilsExtern\\logs\\errors.log.");
            }

            LogWebViewState("WebView2 prêt");
        }

        private async Task WaitForLoginWebViewHostLayoutAsync()
        {
            bool IsHostRenderable()
                => WebViewLayoutReadiness.IsRenderable(
                    LoginWebViewHost.IsLoaded,
                    LoginWebViewHost.ActualWidth,
                    LoginWebViewHost.ActualHeight);

            if (WebViewLayoutReadiness.PrepareLayout(
                IsHostRenderable,
                LoginPanel.UpdateLayout))
            {
                AppLogger.Info(
                    $"YouTube Music WebView host layout ready: " +
                    $"{LoginWebViewHost.ActualWidth:0}x{LoginWebViewHost.ActualHeight:0}");
                return;
            }

            var ready = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
            void CompleteWhenRenderable()
            {
                if (IsHostRenderable())
                {
                    ready.TrySetResult(true);
                }
            }

            void LoadedHandler(object _, RoutedEventArgs __) => CompleteWhenRenderable();
            void SizeChangedHandler(object _, SizeChangedEventArgs __) => CompleteWhenRenderable();

            LoginWebViewHost.Loaded += LoadedHandler;
            LoginWebViewHost.SizeChanged += SizeChangedHandler;
            try
            {
                if (!LoginWebViewHost.DispatcherQueue.TryEnqueue(() =>
                    {
                        LoginPanel.UpdateLayout();
                        CompleteWhenRenderable();
                    }))
                {
                    throw new InvalidOperationException("Impossible de planifier le layout du conteneur WebView2.");
                }

                await ready.Task.WaitAsync(TimeSpan.FromSeconds(10));
                AppLogger.Info(
                    $"YouTube Music WebView host layout ready: " +
                    $"{LoginWebViewHost.ActualWidth:0}x{LoginWebViewHost.ActualHeight:0}");
            }
            finally
            {
                LoginWebViewHost.Loaded -= LoadedHandler;
                LoginWebViewHost.SizeChanged -= SizeChangedHandler;
            }
        }

        private async Task WaitForLoginWebViewLayoutAsync()
        {
            if (WebViewLayoutReadiness.IsRenderable(
                _loginWebView!.IsLoaded,
                _loginWebView.ActualWidth,
                _loginWebView.ActualHeight))
            {
                return;
            }

            var ready = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
            void CompleteWhenRenderable()
            {
                if (WebViewLayoutReadiness.IsRenderable(
                    _loginWebView!.IsLoaded,
                    _loginWebView.ActualWidth,
                    _loginWebView.ActualHeight))
                {
                    ready.TrySetResult(true);
                }
            }

            void LoadedHandler(object _, RoutedEventArgs __) => CompleteWhenRenderable();
            void SizeChangedHandler(object _, SizeChangedEventArgs __) => CompleteWhenRenderable();

            _loginWebView!.Loaded += LoadedHandler;
            _loginWebView.SizeChanged += SizeChangedHandler;
            try
            {
                if (!_loginWebView.DispatcherQueue.TryEnqueue(() =>
                    {
                        _loginWebView.UpdateLayout();
                        CompleteWhenRenderable();
                    }))
                {
                    throw new InvalidOperationException("Impossible de planifier le layout de WebView2.");
                }

                await ready.Task.WaitAsync(TimeSpan.FromSeconds(10));
                LogWebViewState("Layout WebView2 prêt");
            }
            finally
            {
                _loginWebView.Loaded -= LoadedHandler;
                _loginWebView.SizeChanged -= SizeChangedHandler;
            }
        }

        private void LoginWebView_CoreWebView2Initialized(
            WebView2 sender,
            CoreWebView2InitializedEventArgs args)
        {
            if (args.Exception is not null)
            {
                AppLogger.Error(args.Exception, "YouTube Music WebView2 initialization failed");
                ViewModel.Status = $"Initialisation WebView2 impossible: {args.Exception.Message}";
                return;
            }

            LogWebViewState("Événement CoreWebView2Initialized réussi");
        }

        private void LoginWebView_NavigationStarting(
            WebView2 sender,
            CoreWebView2NavigationStartingEventArgs args)
        {
            AppLogger.Info($"YouTube Music WebView navigation starting: {DescribeUri(args.Uri)}");
            ViewModel.Status = "Chargement de la connexion YouTube Music...";
        }

        private void LoginWebView_NavigationCompleted(
            WebView2 sender,
            CoreWebView2NavigationCompletedEventArgs args)
        {
            ContinueYtMusicButton.IsEnabled = args.IsSuccess
                && sender.Source is { Host: var host }
                && host.Equals("music.youtube.com", StringComparison.OrdinalIgnoreCase);

            var message = $"YouTube Music WebView navigation completed: " +
                $"success={args.IsSuccess}; error={args.WebErrorStatus}; uri={DescribeUri(sender.Source?.AbsoluteUri)}";
            if (args.IsSuccess)
            {
                AppLogger.Info(message);
                ViewModel.Status = ContinueYtMusicButton.IsEnabled
                    ? "Connexion détectée. Clique sur Continuer après connexion."
                    : "Page de connexion YouTube Music chargée.";
            }
            else
            {
                var exception = new InvalidOperationException(message);
                AppLogger.Warning(exception, "YouTube Music WebView navigation failed");
                ViewModel.Status = $"Navigation WebView2 impossible: {args.WebErrorStatus}";
            }
        }

        private void LoginWebView_CoreProcessFailed(
            WebView2 sender,
            CoreWebView2ProcessFailedEventArgs args)
        {
            var exception = new InvalidOperationException(
                $"Processus WebView2 arrêté: {args.ProcessFailedKind}; raison={args.Reason}; code={args.ExitCode}.");
            AppLogger.Error(exception, "YouTube Music WebView2 process failed");
            ViewModel.Status = "Le processus WebView2 s'est arrêté. Ferme puis rouvre la connexion.";
        }

        private void LogWebViewState(string step)
        {
            if (_loginWebView == null)
            {
                AppLogger.Info(
                    $"YouTube Music WebView: {step}; control=absent; " +
                    $"hostLoaded={LoginWebViewHost.IsLoaded}; " +
                    $"hostSize={LoginWebViewHost.ActualWidth:0}x{LoginWebViewHost.ActualHeight:0}");
                return;
            }

            AppLogger.Info(
                $"YouTube Music WebView: {step}; loaded={_loginWebView.IsLoaded}; " +
                $"visibility={_loginWebView.Visibility}; size={_loginWebView.ActualWidth:0}x{_loginWebView.ActualHeight:0}; " +
                $"core={(_loginWebView.CoreWebView2 is null ? "null" : "ready")}; " +
                $"source={DescribeUri(_loginWebView.Source?.AbsoluteUri)}");
        }

        private static string DescribeUri(string? value)
        {
            if (!Uri.TryCreate(value, UriKind.Absolute, out var uri))
            {
                return "(aucune)";
            }

            return uri.GetLeftPart(UriPartial.Path);
        }

        private static bool IsYoutubeDomain(string domain)
        {
            var normalizedDomain = domain.TrimStart('.');
            return normalizedDomain.Equals("youtube.com", StringComparison.OrdinalIgnoreCase)
                || normalizedDomain.EndsWith(".youtube.com", StringComparison.OrdinalIgnoreCase);
        }

        private static void SaveCookieFiles(IReadOnlyList<CookieModel> cookies, string netscapeContents)
        {
            var directory = Path.GetDirectoryName(YtMusicDataSource.sessionFile)!;
            Directory.CreateDirectory(directory);
            var suffix = $".tmp-{Guid.NewGuid():N}";
            var sessionTemp = YtMusicDataSource.sessionFile + suffix;
            var ytDlpTemp = YtMusicDataSource.ytdlpCookieFile + suffix;

            try
            {
                File.WriteAllText(sessionTemp, JsonSerializer.Serialize(cookies));
                File.WriteAllText(ytDlpTemp, netscapeContents);
                if (!YtMusicCookieSession.TryLoad(sessionTemp, out _))
                {
                    throw new InvalidDataException("Les cookies YouTube Music générés sont invalides.");
                }

                File.Move(ytDlpTemp, YtMusicDataSource.ytdlpCookieFile, overwrite: true);
                File.Move(sessionTemp, YtMusicDataSource.sessionFile, overwrite: true);
            }
            finally
            {
                TryDeleteTemporaryCookieFile(sessionTemp);
                TryDeleteTemporaryCookieFile(ytDlpTemp);
            }
        }

        private static void TryDeleteTemporaryCookieFile(string path)
        {
            try
            {
                if (File.Exists(path))
                {
                    File.Delete(path);
                }
            }
            catch
            {
                // A temporary cleanup failure must not invalidate a successful connection.
            }
        }

        private void UpdateYtMusicButton()
            => YtMusicButton.Content = YtMusicDataSource.isConnected()
                ? "Déconnexion YouTube Music"
                : "Connexion YouTube Music";
    }
